"""Models for the Agno community integration."""

import logging
from typing import Any, Literal, Protocol

from ag_ui.core.types import Context as AgUiContext
from ag_ui.core.types import Message as AgUiMessage
from ag_ui.core.types import Tool as AgUiTool
from pydantic import BaseModel, Field, model_validator

from digitalkin.models.module.base_types import DataTrigger

logger = logging.getLogger(__name__)


class AgUiRunInput(Protocol):
    """The ``RunAgentInput`` fields the HITL runner reads; ``ag_ui.core.RunAgentInput`` satisfies it."""

    thread_id: str
    run_id: str
    messages: list[AgUiMessage]
    tools: list[AgUiTool] | None


class AgUiStreamInput(DataTrigger):
    """AG-UI 1.0 ``RunAgentInput`` as a module input trigger.

    Legacy ``binary`` parts in user messages, which 1.0 rejects, are upgraded to media parts
    before validation, as ``@ag-ui/client`` 1.x does; the file id is kept in ``metadata.fileId``.
    """

    protocol: Literal["agui_stream"] = "agui_stream"
    thread_id: str = Field(..., description="AG-UI thread identifier.")
    run_id: str = Field(..., description="AG-UI run identifier.")
    messages: list[AgUiMessage] = Field(default_factory=list, description="Conversation messages.")
    tools: list[AgUiTool] = Field(default_factory=list, description="Frontend tools available to the agent.")
    context: list[AgUiContext] = Field(default_factory=list, description="Additional context for the agent.")
    state: Any = Field(default=None, description="Agent state.")
    forwarded_props: Any = Field(default=None, description="Extra properties forwarded to the agent.")

    @model_validator(mode="before")
    @classmethod
    def _upgrade_binary_parts(cls, data: Any) -> Any:
        """Rewrite pre-1.0 ``binary`` content parts into 1.0 image/audio/video/document parts.

        Args:
            data: Raw input.

        Returns:
            The input with every convertible ``binary`` part upgraded and the others dropped.
        """
        if not isinstance(data, dict) or not isinstance(data.get("messages"), list):
            return data
        for message in data["messages"]:
            if not isinstance(message, dict) or not isinstance(message.get("content"), list):
                continue
            parts: list[Any] = []
            for part in message["content"]:
                if not isinstance(part, dict) or part.get("type") != "binary":
                    parts.append(part)
                    continue
                mime = part.get("mimeType") or part.get("mime_type") or ""
                file_id, url, payload, filename = (
                    part.get("id"),
                    part.get("url"),
                    part.get("data"),
                    part.get("filename"),
                )
                if not payload and not url:
                    # TODO(validate): AGUI-BINARY-UPGRADE id-only binary parts cannot become a 1.0 source
                    logger.warning(
                        "[VALIDATE AGUI-BINARY-UPGRADE] message %s: binary part dropped, no url or data "
                        "(id=%s, filename=%s, mime=%s)",
                        message.get("id"),
                        file_id,
                        filename,
                        mime,
                    )
                    continue
                metadata = {key: value for key, value in (("fileId", file_id), ("filename", filename)) if value}
                parts.append({
                    "type": next(
                        (kind for kind in ("image", "audio", "video") if mime.startswith(f"{kind}/")), "document"
                    ),
                    "source": {"type": "data" if payload else "url", "value": payload or url, "mimeType": mime},
                    **({"metadata": metadata} if metadata else {}),
                })
                # TODO(validate): AGUI-BINARY-UPGRADE legacy binary parts still sent by pre-1.x fronts
                logger.info(
                    "[VALIDATE AGUI-BINARY-UPGRADE] message %s: binary part upgraded to %s (%s source, id=%s, "
                    "filename=%s, mime=%s)",
                    message.get("id"),
                    parts[-1]["type"],
                    parts[-1]["source"]["type"],
                    file_id,
                    filename,
                    mime,
                )
            message["content"] = parts
        return data


class PauseInfo(BaseModel):
    """Summary of a paused Agno run.

    Returned by :meth:`AgnoHitlRunner.run` and related methods whenever
    the run paused on one or more external tool calls. Callers typically
    use it to emit the AG-UI awaiting-tool-result event to the front.

    ``new_messages`` carries the AG-UI messages generated by Agno during
    the paused run (user echoes, the assistant message with ``tool_calls``,
    and any tool results emitted before the pause). It's provided because
    Agno does not emit stream events from which the front can reconstruct
    the assistant-with-tool-calls message — in particular, when the LLM
    goes straight from reasoning to a frontend tool call without emitting
    any text. Consumers typically push these messages to the front via a
    :class:`~ag_ui.core.events.MessagesSnapshotEvent` so the client has an
    authoritative view of the conversation.
    """

    thread_id: str
    run_id: str
    pending_tool_call_ids: list[str]
    new_messages: list[AgUiMessage] = Field(default_factory=list)


class ToolOutputMetadata(BaseModel):
    """Cost and execution metadata reported by a tool module itself.

    Enables accurate cost aggregation across modules.

    Attributes:
        response_time_ms: Time taken for the API call(s) in milliseconds.
        api_calls_made: Number of API calls made by the tool.
        cost_estimate_usd: Estimated cost in USD.
        tavily_credits_used: Tavily API credits consumed (if applicable).
        search_depth: Search depth used (basic, advanced, etc.).
        include_raw_content: Whether raw content was requested.
        queries_count: Number of queries executed.
        results_returned: Number of results returned.
        urls_processed: Number of URLs processed (for extract operations).
    """

    response_time_ms: float | None = Field(default=None, description="API response time in ms")
    api_calls_made: int = Field(default=1, description="Number of API calls made")
    cost_estimate_usd: float | None = Field(default=None, description="Estimated cost in USD")
    tavily_credits_used: int | None = Field(default=None, description="Tavily credits consumed")
    search_depth: str | None = Field(default=None, description="Search depth used")
    include_raw_content: bool = Field(default=False, description="Whether raw content was requested")
    queries_count: int = Field(default=1, description="Number of queries executed")
    results_returned: int = Field(default=0, description="Number of results returned")
    urls_processed: int = Field(default=0, description="Number of URLs processed")


class ToolCallMetadata(BaseModel):
    """Metadata from a module tool call including cost and timing information.

    Attributes:
        module_id: The SDK module ID that was called (e.g., "modules:tool_websearch").
        success: Whether the tool call completed successfully.
        duration_ms: Execution time in milliseconds.
        cost_tracked: Whether cost metadata is available from the tool.
        error: Error message if the call failed, None otherwise.
        tool_metadata: Metadata returned by the tool itself (cost, API calls, etc.).
    """

    module_id: str = Field(..., description="The SDK module ID that was called")
    success: bool = Field(..., description="Whether the tool call succeeded")
    duration_ms: float = Field(..., description="Execution time in milliseconds")
    cost_tracked: bool = Field(default=False, description="Whether cost metadata is available from tool")
    error: str | None = Field(default=None, description="Error message if failed")
    tool_metadata: ToolOutputMetadata | None = Field(
        default=None,
        description="Metadata returned by the tool module (cost, API calls, etc.)",
    )

    def to_success_dict(self) -> dict[str, Any]:
        """Convert metadata to dict for successful responses.

        Returns:
            Dictionary with success-relevant fields; error is excluded.
        """
        return self.model_dump(exclude={"error"})

    def to_error_dict(self) -> dict[str, Any]:
        """Convert metadata to dict for error responses.

        Returns:
            Dictionary with error-relevant fields.
        """
        return self.model_dump(include={"module_id", "success", "duration_ms", "error"})

    @staticmethod
    def extract_tool_metadata(output: dict[str, Any]) -> "ToolOutputMetadata | None":
        """Extract tool metadata from a tool's output if present.

        Args:
            output: The tool output dictionary.

        Returns:
            ToolOutputMetadata if metadata is present, None otherwise.
        """
        if not isinstance(output, dict):
            return None

        metadata = output.get("metadata")
        if not metadata or not isinstance(metadata, dict):
            return None

        try:
            return ToolOutputMetadata(
                response_time_ms=metadata.get("response_time_ms"),
                api_calls_made=metadata.get("api_calls_made", 1),
                cost_estimate_usd=metadata.get("cost_estimate_usd"),
                tavily_credits_used=metadata.get("tavily_credits_used"),
                search_depth=metadata.get("search_depth"),
                include_raw_content=metadata.get("include_raw_content", False),
                queries_count=metadata.get("queries_count", 1),
                results_returned=metadata.get("results_returned", 0),
                urls_processed=metadata.get("urls_processed", 0),
            )
        except Exception:
            return None
